/**
 * Idempotently seeds recipes into MongoDB using upsert by title.
 * Returns { inserted, updated, skipped, total }
 */
export const seedRecipes = async () => {
  let inserted = 0;
  let updated = 0;
  let skipped = 0;

  for (const recipeData of sampleRecipes) {
    try {
      const existing = await Recipe.findOne({ title: recipeData.title });

      if (existing) {
        // Idempotent update
        await Recipe.updateOne({ _id: existing._id }, { $set: recipeData }, { runValidators: true });
        updated++;
      } else {
        await Recipe.create(recipeData);
        inserted++;
      }
    } catch (err) {
      console.error(`[Seeder Error] Failed processing recipe '${recipeData.title}':`, err.message);
      skipped++;
    }
  }

  return {
    total: sampleRecipes.length,
    inserted,
    updated,
    skipped,
  };
};

export default seedRecipes;
